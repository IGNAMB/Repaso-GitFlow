  // Método para obtener el idCategoria seleccionado del combo
    private int obtenerIdCategoriaSeleccionado() {
        // Obtén el objeto seleccionado del combo
        Object selectedItem = cbCategorias.getSelectedItem();

        // Si el objeto seleccionado es una instancia de String (nombrecategoria), busca el id en la lista de productos
        if (selectedItem instanceof String) {
            String nombreCategoriaSeleccionada = (String) selectedItem;
            return productoDAO.obtenerIdCategoriaPorNombre(nombreCategoriaSeleccionada);
        }

        // Manejar otros casos si es necesario
        return 0; // O algún valor predeterminado
    }  
    
   private void agregarProducto() {
        try {
            // Obtén los valores de los campos
            int idCategoria = obtenerIdCategoriaSeleccionado(); 
            String nombreProducto = tfNombreProducto.getText();
            String descripcion = tfDescripcion.getText();
            double precio = Double.parseDouble(tfPrecio.getText()); 
            int existencia = Integer.parseInt(tfExistencia.getText());

            // Llama al método insertarProducto de ProductoDAO
            productoDAO.insertarProducto(idCategoria, nombreProducto, descripcion, precio, null, existencia);

            // Actualiza la tabla y limpia los campos
            cargarDatos();
            limpiarCampos();
        } catch (NumberFormatException e) {
            // Manejar la excepción si los valores numéricos no son válidos
            JOptionPane.showMessageDialog(null, "Los valores numéricos no son válidos.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
   
   // Métodos editarProducto, buscarProducto y borrarProducto siguen una estructura similar
   private void editarProducto(Producto2 productoSeleccionado) {
        if (productoSeleccionado != null) {
            // Obtén los valores de los campos
            int idProducto = productoSeleccionado.getIdProducto();
            int idCategoria = productoSeleccionado.getIdCategoria();
            String nombreProducto = tfNombreProducto.getText();
            String descripcion = tfDescripcion.getText();
            double precio = Double.parseDouble(tfPrecio.getText()); 
            int existencia = Integer.parseInt(tfExistencia.getText());

            // Actualiza el producto utilizando el método actualizarProducto de ProductoDAO
            productoDAO.actualizarProducto(idProducto, idCategoria, nombreProducto, descripcion, precio, null, existencia);

            // Actualiza la tabla y limpia los campos
            cargarDatos();
            limpiarCampos();
        } else {
            // Muestra un mensaje indicando que no se ha seleccionado ningún producto
            JOptionPane.showMessageDialog(this, "Selecciona un producto para editar.", "Aviso", JOptionPane.WARNING_MESSAGE);
        }
    }

   private void borrarProducto(Producto2 productoSeleccionado) {
        
        // Llama al método eliminarProducto de ProductoDAO
        productoDAO.eliminarProducto(productoSeleccionado.getIdProducto());

        // Actualiza la tabla y limpia los campos
        cargarDatos();
        limpiarCampos();
    }
   
   private void buscarProducto() {
        // Obtén el nombre del producto a buscar
        String nombreProductoBuscar = tfNombreProducto.getText().trim();

        // Verifica si el nombre del producto a buscar no está vacío
        if (!nombreProductoBuscar.isEmpty()) {
            // Obtén el modelo de la tabla
            ProductoTableModel modelo = (ProductoTableModel) tablaProductos.getModel();

            // Obtén la lista de productos del modelo
            List<Producto2> productos = obtenerProductosDesdeBD();

            // Busca el producto en la lista por el nombre
            Optional<Producto2> productoEncontrado = productos.stream()
                    .filter(producto -> producto.getNombreProducto().equalsIgnoreCase(nombreProductoBuscar))
                    .findFirst();

            // Verifica si se encontró el producto
            if (productoEncontrado.isPresent()) {
                // Obtén el índice de la fila en la tabla
                int rowIndex = productos.indexOf(productoEncontrado.get());

                // Resalta la fila en la tabla
                resaltarFilaEnTabla(rowIndex);
            } else {
                // Muestra un mensaje indicando que el producto no fue encontrado
                JOptionPane.showMessageDialog(this, "Producto no encontrado.", "Aviso", JOptionPane.WARNING_MESSAGE);
            }
        } else {
            // Muestra un mensaje indicando que el campo de búsqueda está vacío
            JOptionPane.showMessageDialog(this, "Ingresa el nombre del producto a buscar.", "Aviso", JOptionPane.WARNING_MESSAGE);
        }
    }

    private void resaltarFilaEnTabla(int rowIndex) {
        // Obtén el modelo de la tabla
        ProductoTableModel modelo = (ProductoTableModel) tablaProductos.getModel();

        // Obtén el sorter de la tabla
        RowSorter<? extends TableModel> sorter = tablaProductos.getRowSorter();

        // Convierte el índice de la fila al índice de la fila en el modelo
        int modelRowIndex = tablaProductos.convertRowIndexToModel(rowIndex);

        // Selecciona y resalta la fila en la tabla
        tablaProductos.setRowSelectionInterval(modelRowIndex, modelRowIndex);

        // Desplaza la vista de la tabla para mostrar la fila seleccionada
        tablaProductos.scrollRectToVisible(tablaProductos.getCellRect(modelRowIndex, 0, true));
    }

    // Método para limpiar los campos
    private void limpiarCampos() {
        tfNombreProducto.setText("");
        tfDescripcion.setText("");
        tfPrecio.setText("");
        tfExistencia.setText("");
        cbCategorias.setSelectedIndex(0); // O el índice deseado para la opción predeterminada
    }
    
