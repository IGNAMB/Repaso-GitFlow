    private void actualizarCamposDesdeTabla(int filaSeleccionada) {
        // Obtener el producto desde el modelo basado en la fila seleccionada
        ProductoTableModel modelo = (ProductoTableModel) tablaProductos.getModel();
        productoSeleccionado = modelo.getProductoAt(filaSeleccionada);

        // Actualizar los campos con los datos del producto
        idProductoSeleccionado = productoSeleccionado.getIdProducto();
        tfNombreProducto.setText(productoSeleccionado.getNombreProducto());
        tfDescripcion.setText(productoSeleccionado.getDescripcion());
        tfPrecio.setText(String.valueOf(productoSeleccionado.getPrecio()));
        tfExistencia.setText(String.valueOf(productoSeleccionado.getExistencia()));

        // Seleccionar la categoría en el ComboBox
        seleccionarCategoriaEnComboBox(cbCategorias, productoSeleccionado.getNombreCategoria());
    }

    public void seleccionarCategoriaEnComboBox(JComboBox<String> comboBox, String nombreCategoria) {
        DefaultComboBoxModel<String> model = (DefaultComboBoxModel<String>) comboBox.getModel();

        for (int i = 0; i < model.getSize(); i++) {
            String categoria = model.getElementAt(i);
            if (categoria.equals(nombreCategoria)) {
                comboBox.setSelectedIndex(i);
                return; // Termina el bucle una vez que se encuentra la categoría
            }
        }
    }
    
