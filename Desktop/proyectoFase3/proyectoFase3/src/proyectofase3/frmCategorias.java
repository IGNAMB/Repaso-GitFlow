    private void agregarCategoria() {
        // Obtén los valores de los campos
        String nombreCategoria = tfDescripcion.getText();

        // Crea una instancia de Categoria con los valores
        Categoria nuevaCategoria = new Categoria();
        nuevaCategoria.setNombreCategoria(nombreCategoria); 

        // Llama al método insertarCategoria de CategoriaDAO
        categoriaDAO.gestionarCategoria("I", 0, nombreCategoria);

        // Actualiza la tabla y limpia los campos
        actualizarTablaCategorias();
        limpiarCamposCategorias();
    }

    private void editarCategoria() {
        // Obtén los valores de los campos
        int idCategoria = obtenerIdCategoriaSeleccionada();
        String nombreCategoria = tfDescripcion.getText();

        // Crea una instancia de Categoria con los valores
        Categoria categoriaEditada = new Categoria();
        categoriaEditada.setIdCategoria(idCategoria);
        categoriaEditada.setNombreCategoria(nombreCategoria); 

        // Llama al método actualizarCategoria de CategoriaDAO
        categoriaDAO.gestionarCategoria("U", categoriaEditada.getIdCategoria(), categoriaEditada.getNombreCategoria());

        // Actualiza la tabla y limpia los campos
        actualizarTablaCategorias();
        limpiarCamposCategorias();
    }

    private void buscarCategoria() {
        // Obtén el nombre de la categoría a buscar
        String nombreCategoriaABuscar = tfDescripcion.getText();

        // Llama al método buscarCategoriaPorNombre de CategoriaDAO
        Categoria categoriaEncontrada = categoriaDAO.buscarCategoriaPorNombre(nombreCategoriaABuscar);

        if (categoriaEncontrada != null) {
            // Muestra la descripción en tfDescripcion
            tfDescripcion.setText(categoriaEncontrada.getNombreCategoria());

            // Actualiza la tabla para resaltar la categoría encontrada
            resaltarCategoriaEnTabla(nombreCategoriaABuscar);
        } else {
            // Limpiar tfDescripcion si no se encuentra la categoría
            tfDescripcion.setText("");
        }
    }

    private void borrarCategoria() {
        // Obtén el ID de la categoría seleccionada
        int idCategoria = obtenerIdCategoriaSeleccionada();

        // Llama al método eliminarCategoria de CategoriaDAO
        categoriaDAO.gestionarCategoria("D", idCategoria, "");

        // Actualiza la tabla y limpia los campos
        actualizarTablaCategorias();
        limpiarCamposCategorias();
    }

    private void mostrarDescripcionCategoriaSeleccionada() {
        // Obtén el nombre de la categoría seleccionada
        String nombreCategoriaSeleccionada = obtenerNombreCategoriaSeleccionada();

        // Llama al método obtenerDescripcionCategoriaPorNombre de CategoriaDAO
        String descripcion = categoriaDAO.obtenerDescripcionCategoriaPorNombre(nombreCategoriaSeleccionada);

        // Muestra la descripción en tfDescripcion
        tfDescripcion.setText(descripcion);
    }

    private void actualizarTablaCategorias() {
        // Limpia la tabla antes de cargar nuevos datos
        modeloTablaCategorias.clear();

        // Carga nuevos datos desde la base de datos
        List<Categoria> categorias = categoriaDAO.obtenerCategoriasDesdeBaseDeDatos();

        // Agrega las nuevas filas a la tabla
        for (Categoria categoria : categorias) {
            modeloTablaCategorias.addRow(new Object[]{categoria.getIdCategoria(), categoria.getNombreCategoria()});
        }
    }

    private void limpiarCamposCategorias() {
        // Limpia los campos de texto
        tfDescripcion.setText("");
    }

    private int obtenerIdCategoriaSeleccionada() {
        // Obtén el índice de la fila seleccionada en la tabla
        int filaSeleccionada = tablaCategorias.getSelectedRow();

        // Obtiene el ID de la categoría en la fila seleccionada
        return (int) modeloTablaCategorias.getValueAt(filaSeleccionada, 0);
    }

    private String obtenerNombreCategoriaSeleccionada() {
        // Obtén el índice de la fila seleccionada en la tabla
        int filaSeleccionada = tablaCategorias.getSelectedRow();

        // Obtiene el nombre de la categoría en la fila seleccionada
        return (String) modeloTablaCategorias.getValueAt(filaSeleccionada, 1);
    }

    private void resaltarCategoriaEnTabla(String nombreCategoria) {
        // Itera sobre las filas de la tabla
        for (int i = 0; i < tablaCategorias.getRowCount(); i++) {
            // Obtiene el nombre de la categoría en la fila actual
            String nombreEnFila = (String) modeloTablaCategorias.getValueAt(i, 1);

            // Compara el nombre de la categoría en la fila actual con el nombre buscado
            if (nombreEnFila.equals(nombreCategoria)) {
                // Selecciona la fila y sale del bucle
                tablaCategorias.setRowSelectionInterval(i, i);
                break;
            }
        }
    }
    
