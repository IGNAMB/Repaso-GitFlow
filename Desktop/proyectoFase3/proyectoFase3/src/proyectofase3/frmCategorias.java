     private void cargarDatosCategorias() {
        List<Categoria> categorias = categoriaDAO.obtenerCategoriasDesdeBaseDeDatos();
        modeloTablaCategorias = new CategoriaTableModel();
        modeloTablaCategorias.clear();
        // Agregar las filas al modelo de categorías
        for (Categoria categoria : categorias) {
            modeloTablaCategorias.agregarFila(
                categoria.getIdCategoria(),
                categoria.getNombreCategoria() 
            );
        }

        // Establecer el modelo en la tabla de categorías
        tablaCategorias.setModel(modeloTablaCategorias);
    }

